#!/usr/bin/env python3
"""Score a driver.py run. usage: check.py <run_dir>"""
import json, os, re, subprocess, sys

RUN = sys.argv[1]
R = json.load(open(f"{RUN}/results.json"))
PSI = "ψ"
NAME = re.compile(r"^\d{4}-\d{2}-\d{2}_\d{2}-\d{2}_.+\.md$")
SIG = re.compile(r"Generated by Witchaphon feat\. Test Oracle - Claude Code \S")
EXTRA = ("decisions locked", "uncommitted wip", "open questions", "suggested skills", "still running")
rows = []


def ok(scen, what, cond, detail=""):
    rows.append((scen, "PASS" if cond else "FAIL", what, "" if cond else str(detail)[:160]))


def git(repo, *a):
    return subprocess.run(["git", "-C", repo, *a], capture_output=True, text=True).stdout.strip()


def forward_only(tools):
    return any(t.startswith("Skill(forward|") and "--only" in t for t in tools)


def common_reply(scen, reply, doc):
    reply = reply or ""
    ok(scen, "reply has a code block", "```" in reply, reply[:120])
    ok(scen, "prompt names the doc file", bool(doc) and doc in reply, doc)
    ok(scen, "prompt says Next Session", "next session" in reply.lower())


def check_oracle(S):
    t, repo = R[S], f"{RUN}/{S}/test-oracle"
    docs, st, tools = t["psi_docs"], t["state"], t["tools"]
    doc = docs[0] if docs else ""
    ok(S, "one doc in ψ/inbox/handoff, forward's name format", len(docs) == 1 and NAME.match(doc), docs)
    ok(S, "nothing in .claude/handovers", not t["claude_handovers"], t["claude_handovers"])
    hs = " ".join(t["doc_headings"]).lower()
    ok(S, "doc has Next Session", "next session" in hs, t["doc_headings"])
    ok(S, "doc has an extra section", any(e in hs for e in EXTRA), t["doc_headings"])
    feat = git(repo, "log", "--format=%h", "--grep", "^feat(TASK-42)")
    body = open(f"{repo}/{PSI}/inbox/handoff/{doc}", errors="ignore").read() if doc else ""
    ok(S, "doc cites the feat SHA", bool(feat) and feat[:7] in body, feat)
    ok(S, "HEAD is a handoff commit", st["head"].split(" ", 1)[1].startswith("handoff"), st["head"])
    want = {f"{PSI}/inbox/handoff/{doc}", f"{PSI}/memory/learnings/2026-10-17_greeting-lowercase.md"}
    ok(S, "commit = doc + this session's ψ note, nothing else", set(st["head_files"]) == want, st["head_files"])
    ok(S, "Rule 8 signature last line", bool(SIG.search(st["head_last_line"])), st["head_last_line"])
    ok(S, "pushed", st.get("remote_head_equals_local") is True)
    ok(S, "other window's notes.md untouched", " M notes.md" in st["status"], st["status"])
    ok(S, "other window's ψ note untracked", f"?? {PSI}/memory/other-window-note.md" in st["status"], st["status"])
    ok(S, "called forward --only", forward_only(tools), tools)
    ok(S, "no plan mode", not any(x in ("EnterPlanMode", "ExitPlanMode") for x in tools), tools)
    ok(S, "did not call /handoff", not any(x.startswith("Skill(handoff|") for x in tools), tools)
    common_reply(S, t["r2_reply"], doc)
    if "rerun" not in t:
        return
    rr = t["rerun"]
    ok("T4", "re-run: still one doc", rr.get("psi_docs") == docs, rr.get("psi_docs"))
    ok("T4", "re-run: no new commit", rr.get("head_unchanged") is True)
    ok("T4", "re-run: forward not called again", not forward_only(rr.get("tools", [])), rr.get("tools"))
    common_reply("T4", rr.get("reply"), doc)

for S in ("T1", "T1b", "T6"):
    if S in R and "crash" not in R[S]:
        check_oracle(S)

if "T6" in R and "crash" not in R["T6"]:
    rep, subj = R["T6"]["r2_reply"] or "", R["T6"]["state"]["head"]
    has_th = lambda s: any("\u0e00" <= ch <= "\u0e7f" for ch in s)
    ok("T6", "Thai session: prompt in Thai", has_th(rep), rep[:120])
    ok("T6", "Thai session: prompt keeps the heading name Next Session", "Next Session" in rep, rep[:200])
    ok("T6", "Thai session: commit subject in Thai", has_th(subj), subj)

if "T2" in R and "crash" not in R["T2"]:
    t = R["T2"]
    docs = t["oracle_psi_docs"]
    doc = docs[0] if docs else ""
    ok("T2", "doc landed in the oracle repo via the ψ symlink", len(docs) == 1 and NAME.match(doc), docs)
    ok("T2", "nothing in product .claude/handovers", not t["product_claude_handovers"])
    ok("T2", "oracle HEAD is a handoff commit", t["oracle_state"]["head"].split(" ", 1)[1].startswith("handoff"), t["oracle_state"]["head"])
    ok("T2", "oracle commit is only the doc", t["oracle_state"]["head_files"] == [f"{PSI}/inbox/handoff/{doc}"], t["oracle_state"]["head_files"])
    ok("T2", "oracle pushed", t["oracle_state"].get("remote_head_equals_local") is True)
    ok("T2", "product HEAD still feat: app", t["product_state"]["head"].endswith("feat: app"), t["product_state"]["head"])
    ok("T2", "product not pushed", t["product_state"].get("remote_head_equals_local") is False)
    ok("T2", "called forward --only", forward_only(t["tools"]), t["tools"])
    common_reply("T2", t["r2_reply"], doc)

if "T3" in R and "crash" not in R["T3"]:
    t = R["T3"]
    hv = t["claude_handovers"]
    doc = hv[0] if hv else ""
    ok("T3", "doc in .claude/handovers", len(hv) == 1 and NAME.match(doc), hv)
    ok("T3", "no stray ψ created", t["psi_created"] is False)
    ok("T3", "no commit (HEAD still feat: page)", t["state"]["head"].endswith("feat: page") and t["state"]["commits"] == 2, t["state"]["head"])
    ok("T3", "forward not called", not any(x.startswith("Skill(forward|") for x in t["tools"]), t["tools"])
    common_reply("T3", t["r2_reply"], doc)

if "T5" in R and "crash" not in R["T5"]:
    t = R["T5"]
    skills = [x for x in t["tools"] if x.startswith("Skill(")]
    ok("T5", "long sentence routed to handover", any(x.startswith("Skill(handover") for x in skills), skills)
    ok("T5", "long sentence: no /handoff temp file", not any(x.startswith("Skill(handoff|") for x in skills), skills)
    ok("T5", "long sentence: no plan mode", not any(x in ("EnterPlanMode", "ExitPlanMode") for x in t["tools"]), t["tools"])

for s, v in R.items():
    if "crash" in v:
        rows.append((s, "FAIL", "scenario crashed", v["crash"][:160]))
w = max(len(r[2]) for r in rows) if rows else 10
for s, res, what, det in rows:
    print(f"{s:3} {res:4}  {what:<{w}}  {det}")
fails = sum(r[1] == "FAIL" for r in rows)
print(f"\n{len(rows) - fails}/{len(rows)} pass" + "".join(f" | {s} secs={v.get('secs')}" for s, v in R.items() if "secs" in v))
